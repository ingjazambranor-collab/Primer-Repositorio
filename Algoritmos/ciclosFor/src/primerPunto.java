public class primerPunto {
    public static void main(String[] args) {

        System.out.println("Ascendente:");
        for (int i = 0; i <= 100; i++) {
            System.out.print(i + " ");
        }

        System.out.println("\n\nDescendente:");
        for (int i = 100; i >= 0; i--) {
            System.out.print(i + " ");
        }
    }
}